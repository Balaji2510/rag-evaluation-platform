export class ResultDetailComponent implements OnInit {
  private readonly route = inject(ActivatedRoute);
  private readonly evaluationService = inject(EvaluationService);

  runId = '';
  resultId = '';
  result = signal<EvaluationResult | null>(null);
  loading = signal<boolean>(true);
  errorMessage = signal<string | null>(null);

  // Phase 10: Human evaluation & Annotations state
  selectedHumanScore = signal<number | null>(null);
  humanFeedbackText = '';
  savingHuman = signal<boolean>(false);
  newTagInput = '';

  ngOnInit(): void {
    this.runId = this.route.snapshot.params['id'];
    this.resultId = this.route.snapshot.params['resultId'];
    this.loadResult();
  }

  loadResult(): void {
    this.loading.set(true);
    this.errorMessage.set(null);

    this.evaluationService.getSingleEvaluationResult(this.runId, this.resultId).subscribe({
      next: (data) => {
        this.result.set(data);
        if (data.humanScore) {
          this.selectedHumanScore.set(data.humanScore);
        }
        if (data.humanFeedback) {
          this.humanFeedbackText = data.humanFeedback;
        }
        this.loading.set(false);
      },
      error: (err) => {
        this.errorMessage.set(err.error?.error?.message || 'Could not load evaluation question result.');
        this.loading.set(false);
      },
    });
  }

  saveHumanEval(): void {
    const score = this.selectedHumanScore();
    if (!score) {
      alert('Please select a star rating first.');
      return;
    }
    this.savingHuman.set(true);
    this.evaluationService
      .submitHumanEval(this.runId, this.resultId, score, this.humanFeedbackText)
      .subscribe({
        next: () => {
          this.savingHuman.set(false);
          const current = this.result();
          if (current) {
            this.result.set({
              ...current,
              humanScore: score,
              humanFeedback: this.humanFeedbackText,
            });
          }
        },
        error: () => {
          this.savingHuman.set(false);
          alert('Failed to save human review.');
        },
      });
  }

  addTag(): void {
    const tag = this.newTagInput.trim();
    if (!tag) return;
    const current = this.result();
    if (!current) return;
    const tags = [...(current.annotations || [])];
    if (!tags.includes(tag)) {
      tags.push(tag);
      this.evaluationService.submitAnnotations(this.runId, this.resultId, tags).subscribe({
        next: () => {
          this.newTagInput = '';
          this.result.set({ ...current, annotations: tags });
        },
        error: () => alert('Failed to add annotation tag.'),
      });
    }
  }

  removeTag(tag: string): void {
    const current = this.result();
    if (!current) return;
    const tags = (current.annotations || []).filter((t) => t !== tag);
    this.evaluationService.submitAnnotations(this.runId, this.resultId, tags).subscribe({
      next: () => {
        this.result.set({ ...current, annotations: tags });
      },
      error: () => alert('Failed to remove tag.'),
    });
  }

  getScoreTierClass(score: number | null | undefined): string {
    if (score === null || score === undefined) return 'tier-neutral';
    if (score >= 0.8) return 'tier-good';
    if (score >= 0.5) return 'tier-warning';
    return 'tier-poor';
  }

  getTierLabel(score: number | null | undefined): string {
    if (score === null || score === undefined) return 'N/A';
    if (score >= 0.8) return 'Good';
    if (score >= 0.5) return 'Warning';
    return 'Poor';
  }

  getScorePercent(score: number | null | undefined): number {
    if (score === null || score === undefined) return 0;
    return Math.min(100, Math.max(0, Math.round(score * 100)));
  }

  formatScore(score: number | null | undefined): string {
    if (score === null || score === undefined) return '—';
    return score.toFixed(2);
  }
}
