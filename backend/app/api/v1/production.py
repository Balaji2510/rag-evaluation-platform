# --- Workspaces (Team Support) ---

@router.get("/workspaces", response_model=List[WorkspaceResponse])
async def list_workspaces(
    current_user: UserResponse = Depends(get_current_user),
    prod_service: ProductionService = Depends(get_production_service),
) -> List[WorkspaceResponse]:
    """List workspaces the current user belongs to."""
    ws = await prod_service.workspace_repo.list_for_user(current_user.id)
    return [
        WorkspaceResponse(
            id=w.id,
            name=w.name,
            ownerId=w.ownerId,
            members=w.members,
            createdAt=w.createdAt,
        )
        for w in ws
    ]


@router.post("/workspaces", response_model=WorkspaceResponse, status_code=status.HTTP_201_CREATED)
async def create_workspace(
    payload: WorkspaceCreate,
    current_user: UserResponse = Depends(get_current_user),
    prod_service: ProductionService = Depends(get_production_service),
) -> WorkspaceResponse:
    """Create a new team workspace."""
    w = Workspace(
        id=str(uuid.uuid4()),
        name=payload.name,
        ownerId=current_user.id,
        members=payload.members or [{"userId": current_user.id, "role": "owner"}],
    )
    saved = await prod_service.workspace_repo.create(w)
    return WorkspaceResponse(
        id=saved.id,
        name=saved.name,
        ownerId=saved.ownerId,
        members=saved.members,
        createdAt=saved.createdAt,
    )

