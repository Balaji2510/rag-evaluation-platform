# --- Human Evaluation & Annotations ---

@router.post("/evaluations/{evaluation_id}/results/{result_id}/human-eval")
async def record_human_eval(
    evaluation_id: str,
    result_id: str,
    payload: HumanEvalRequest,
    current_user: UserResponse = Depends(get_current_user),
    prod_service: ProductionService = Depends(get_production_service),
):
    """Submit human reviewer score and feedback on a question result."""
    success = await prod_service.record_human_eval(result_id, payload.humanScore, payload.humanFeedback)
    if not success:
        raise AppException("Could not update human evaluation", status_code=400)
    return {"message": "Human evaluation recorded successfully", "resultId": result_id}


@router.post("/evaluations/{evaluation_id}/results/{result_id}/annotations")
async def set_result_annotations(
    evaluation_id: str,
    result_id: str,
    payload: AnnotationRequest,
    current_user: UserResponse = Depends(get_current_user),
    prod_service: ProductionService = Depends(get_production_service),
):
    """Set label annotations on a question evaluation result."""
    success = await prod_service.set_annotations(result_id, payload.annotations)
    if not success:
        raise AppException("Could not update annotations", status_code=400)
    return {"message": "Annotations updated successfully", "resultId": result_id}


